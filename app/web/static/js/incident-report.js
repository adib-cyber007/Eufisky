(function () {
  function valueOrFallback(value) {
    if (Array.isArray(value)) return value.length ? value.join("; ") : "Not captured";
    return String(value || "Not captured");
  }

  function text(call, detail) {
    const incident = detail.incident || {};
    const summary = incident.summary || {};
    const started = call.started_at ? new Date(call.started_at).toLocaleString() : "Not captured";
    return [
      "Eufisky incident report",
      `Caller: ${call.from_label || call.from_phone || "Withheld number"}`,
      `Call time: ${started}`,
      `Peak risk: ${Number(call.peak_risk) || 0} / 100`,
      "",
      "Summary",
      valueOrFallback(summary.summary),
      "",
      `Caller claimed: ${valueOrFallback(summary.caller_claim)}`,
      `Asked for: ${valueOrFallback(summary.requests_made)}`,
      `Margaret shared: ${valueOrFallback(summary.disclosed_by_senior)}`,
      `Intervention: ${valueOrFallback(summary.intervention)}`,
      `Outcome: ${valueOrFallback(summary.outcome)}`,
      `Recommendation: ${valueOrFallback(summary.recommendation)}`,
      "",
      "Redacted transcript",
      valueOrFallback(incident.redacted_transcript),
      "",
      "Generated by Eufisky. Verify urgent claims through an official phone number.",
    ].join("\n");
  }

  async function copy(value) {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(value);
      return;
    }
    const field = document.createElement("textarea");
    field.value = value;
    field.setAttribute("readonly", "");
    field.style.position = "fixed";
    field.style.opacity = "0";
    document.body.append(field);
    field.select();
    const copied = document.execCommand("copy");
    field.remove();
    if (!copied) throw new Error("Copy was not available");
  }

  window.EufiskyIncidentReport = { copy, text, valueOrFallback };
})();
