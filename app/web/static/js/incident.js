(function () {
  const root = document.querySelector("#print-report");
  const parts = location.pathname.split("/").filter(Boolean);
  const room = decodeURIComponent(parts.at(-2) || "demo");
  const callId = decodeURIComponent(parts.at(-1) || "");

  function element(tag, className, text) {
    const node = document.createElement(tag);
    if (className) node.className = className;
    if (text !== undefined) node.textContent = text;
    return node;
  }

  function fact(label, value) {
    const wrapper = element("div");
    wrapper.append(
      element("dt", "", label),
      element("dd", "", window.EufiskyIncidentReport.valueOrFallback(value)),
    );
    return wrapper;
  }

  function render(call) {
    const incident = call.incident || {};
    const summary = incident.summary || {};
    document.title = `${call.from_label || call.from_phone || "Incident"} — Eufisky report`;
    root.replaceChildren();

    const masthead = element("header", "print-masthead");
    const brand = element("div");
    brand.append(element("span", "print-mark", "E"), element("b", "", "Eufisky"));
    masthead.append(brand, element("span", "", "Redacted family safety report"));

    const heading = element("section", "print-heading");
    const headingCopy = element("div");
    headingCopy.append(
      element("p", "", "Incident report"),
      element("h1", "", call.from_label || call.from_phone || "Withheld number"),
      element("time", "", call.started_at ? new Date(call.started_at).toLocaleString() : "Time not captured"),
    );
    const score = element("div", "print-score");
    score.append(element("strong", "", String(Number(call.peak_risk) || 0)), element("span", "", "Peak risk / 100"));
    heading.append(headingCopy, score);

    const summaryBlock = element("section", "print-summary");
    summaryBlock.append(element("h2", "", "What happened"), element("p", "", summary.summary || "Incident summary unavailable."));

    const facts = element("dl", "print-facts");
    facts.append(
      fact("Caller claimed", summary.caller_claim),
      fact("Asked for", summary.requests_made),
      fact("Margaret shared", summary.disclosed_by_senior),
      fact("Intervention", summary.intervention),
      fact("Outcome", summary.outcome),
      fact("Recommendation", summary.recommendation),
    );

    const transcript = element("section", "print-transcript");
    transcript.append(element("h2", "", "Redacted transcript"), element("pre", "", incident.redacted_transcript || "No transcript was captured."));

    const actions = element("div", "print-actions");
    const copy = element("button", "button secondary", "Copy incident report");
    const print = element("button", "button call", "Print or save as PDF");
    const feedback = element("span", "copy-feedback");
    feedback.setAttribute("role", "status");
    copy.addEventListener("click", async () => {
      try {
        await window.EufiskyIncidentReport.copy(window.EufiskyIncidentReport.text(call, call));
        feedback.textContent = "Report copied.";
      } catch (error) {
        feedback.textContent = "Copy was not available in this browser.";
      }
    });
    print.addEventListener("click", () => window.print());
    actions.append(copy, print, feedback);

    const footer = element("footer", "print-footer", "Generated by Eufisky · Sensitive values remain redacted · Verify urgent claims through an official phone number.");
    root.append(masthead, heading, summaryBlock, facts, transcript, actions, footer);
  }

  fetch(`/api/rooms/${encodeURIComponent(room)}/calls/${encodeURIComponent(callId)}`)
    .then((response) => {
      if (!response.ok) throw new Error("Report not found");
      return response.json();
    })
    .then((call) => {
      if (!call.features?.incident_export || !call.incident) throw new Error("Report not available");
      render(call);
    })
    .catch(() => {
      root.replaceChildren(
        element("h1", "", "Report unavailable"),
        element("p", "error-copy", "This incident report could not be loaded. Return to the family dashboard and try again."),
      );
    });
})();
